"""SMB and NFS shares of other devices, mounted under /mnt/remotes/<name>.

Settings live in /etc/dahlia/remotes.json, SMB credentials in
/etc/dahlia/remotes/<name>.cred (root, 0600). Each share gets a generated
mount unit and an automount unit in /etc/systemd/system, like the disks:
no /etc/fstab, and a device that is off does not hold up the boot. The
automount mounts on first access and keeps it mounted.

Before anything is saved the share is mounted once on a temporary
directory, so a wrong password or path is reported right away.

SMB files belong to dahlia-apps:dahlia (mode 0664/0775), so apps can use
them; NFS keeps the owners the other device reports.
"""

import contextlib
import json
import os
import re
from pathlib import Path

from .actions import Context, Param, action
from .protocol import FAILED, INVALID_PARAMS, AgentError
from .settings import read_json, show_props, write_file

REMOTES_ROOT = "/mnt/remotes"
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,31}$")
HOST_RE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$")
SMB_SHARE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._$-]{0,79}$")
NFS_PATH_RE = re.compile(r"^/(?:[A-Za-z0-9._-][A-Za-z0-9 ._-]{0,99}(?:/|$)){0,10}$")
SMB_USER_RE = re.compile(r"^[A-Za-z0-9._@-]{1,64}$")
# Printable, no line breaks: the credentials file is read line by line.
PASSWORD_RE = re.compile(r"^[^\x00-\x1f\x7f]{0,256}$")
TYPES = ("smb", "nfs")
APPS_USER = "dahlia-apps"
DATA_GROUP = "dahlia"
NFS_OPTIONS = "soft,timeo=300,retrans=4"
MOUNT_TIMEOUT = 30


def config_file(ctx: Context) -> Path:
    return ctx.etc / "dahlia/remotes.json"


def cred_file(ctx: Context, name: str) -> Path:
    return ctx.etc / "dahlia/remotes" / f"{name}.cred"


def mountpoint(ctx: Context, name: str) -> Path:
    return ctx.remotes / name


def unit_base(ctx: Context, name: str) -> str:
    """systemd-escape --path of the mount point."""
    parts = str(mountpoint(ctx, name)).strip("/").split("/")
    return "-".join(p.replace("-", "\\x2d") for p in parts)


def unit_dir(ctx: Context) -> Path:
    return ctx.etc / "systemd/system"


def load(ctx: Context) -> list[dict]:
    data = read_json(config_file(ctx), {})
    out = []
    for r in data.get("remotes") if isinstance(data.get("remotes"), list) else []:
        if not isinstance(r, dict) or not NAME_RE.match(str(r.get("name", ""))):
            continue
        if r.get("type") not in TYPES or not HOST_RE.match(str(r.get("host", ""))):
            continue
        share_re = SMB_SHARE_RE if r["type"] == "smb" else NFS_PATH_RE
        if not share_re.match(str(r.get("share", ""))):
            continue
        user = r.get("username") if isinstance(r.get("username"), str) else ""
        out.append({"name": r["name"], "type": r["type"], "host": r["host"], "share": r["share"],
                    "username": user if r["type"] == "smb" and SMB_USER_RE.match(user) else "",
                    "readonly": r.get("readonly") is True})
    return out


def save(ctx: Context, remotes: list[dict]) -> None:
    remotes = sorted(remotes, key=lambda r: r["name"])
    write_file(config_file(ctx), json.dumps({"remotes": remotes}, indent=2) + "\n")


def ids(ctx: Context) -> tuple[int, int]:
    uid = int(ctx.runner.run(["getent", "passwd", APPS_USER]).stdout.split(":")[2])
    gid = int(ctx.runner.run(["getent", "group", DATA_GROUP]).stdout.split(":")[2])
    return uid, gid


def what(r: dict) -> str:
    if r["type"] == "smb":
        return f"//{r['host']}/{r['share']}"
    return f"{r['host']}:{r['share']}"


def options(ctx: Context, r: dict, cred: Path) -> str:
    if r["type"] == "smb":
        uid, gid = ids(ctx)
        opts = [f"credentials={cred}" if r["username"] else "guest", f"uid={uid}", f"gid={gid}",
                "file_mode=0664", "dir_mode=0775", "iocharset=utf8", "noperm"]
    else:
        opts = [NFS_OPTIONS]
    if r["readonly"]:
        opts.append("ro")
    return ",".join(opts)


def render_mount(ctx: Context, r: dict) -> str:
    # % is a specifier in unit files; the patterns above do not allow it.
    return (
        "# Generated by dahlia-agent from /etc/dahlia/remotes.json. Do not edit.\n"
        "[Unit]\n"
        f"Description=Dahlia remote share {r['name']} ({what(r)})\n"
        "After=network-online.target\nWants=network-online.target\n\n"
        "[Mount]\n"
        f"What={what(r)}\n"
        f"Where={mountpoint(ctx, r['name'])}\n"
        f"Type={'cifs' if r['type'] == 'smb' else 'nfs'}\n"
        f"Options={options(ctx, r, cred_file(ctx, r['name']))},_netdev,nofail\n"
        f"TimeoutSec={MOUNT_TIMEOUT}\n"
    )


def render_automount(ctx: Context, r: dict) -> str:
    return (
        "# Generated by dahlia-agent from /etc/dahlia/remotes.json. Do not edit.\n"
        "[Unit]\n"
        f"Description=Dahlia remote share {r['name']} (mounted on access)\n\n"
        "[Automount]\n"
        f"Where={mountpoint(ctx, r['name'])}\n"
        "TimeoutIdleSec=0\n\n"
        "[Install]\nWantedBy=remote-fs.target\n"
    )


def write_cred(path: Path, username: str, password: str) -> None:
    write_file(path, f"username={username}\npassword={password}\n", mode=0o600)


def test_mount(ctx: Context, r: dict, password: str | None) -> None:
    """Mount once on a temporary directory; AgentError with the reason if it fails."""
    tmp = ctx.run_dir / "remote-test"
    tmp.mkdir(parents=True, exist_ok=True)
    cred = ctx.run_dir / "remote-test.cred"
    if r["type"] == "smb" and r["username"]:
        if password is None:
            old = cred_file(ctx, r["name"])
            if not old.exists():
                raise AgentError(INVALID_PARAMS, "password is missing")
            write_file(cred, old.read_text(), mode=0o600)
        else:
            write_cred(cred, r["username"], password)
    try:
        proc = ctx.runner.run(
            ["mount", "-t", "cifs" if r["type"] == "smb" else "nfs", what(r), str(tmp),
             "-o", options(ctx, r, cred)], timeout=MOUNT_TIMEOUT + 10, check=False)
        if proc.returncode != 0:
            lines = [ln for ln in (proc.stderr or proc.stdout or "").splitlines() if ln.strip()]
            raise AgentError(FAILED, f"mount: {lines[-1] if lines else proc.returncode}")
        ctx.runner.run(["umount", str(tmp)], check=False)
    finally:
        cred.unlink(missing_ok=True)


def mount_state(ctx: Context, name: str) -> str:
    """mounted, idle (waits for the first access), error or off."""
    target = str(mountpoint(ctx, name))
    fstypes = set()
    try:
        for line in (ctx.proc / "self/mounts").read_text().splitlines():
            f = line.split()
            if len(f) >= 3 and f[1] == target:
                fstypes.add(f[2])
    except OSError:
        pass
    if fstypes & {"cifs", "smb3", "nfs", "nfs4"}:
        return "mounted"
    base = unit_base(ctx, name)
    mount = show_props(ctx, ["systemctl", "show", f"{base}.mount", "-p", "Result"])
    if mount.get("Result") not in (None, "", "success"):
        return "error"
    return "idle" if "autofs" in fstypes else "off"


def apps_using(ctx: Context, name: str) -> list[str]:
    """Installed apps with a folder on this remote share."""
    prefix = f"{mountpoint(ctx, name)}/"
    out = []
    apps_dir = ctx.var / "apps"
    if not apps_dir.is_dir():
        return out
    for d in sorted(apps_dir.iterdir()):
        state = read_json(d / "state.json", {})
        folders = state.get("folders") if isinstance(state.get("folders"), dict) else {}
        if any(isinstance(v, str) and (v + "/").startswith(prefix) for v in folders.values()):
            out.append(d.name)
    return out


def stop_units(ctx: Context, name: str) -> None:
    base = unit_base(ctx, name)
    ctx.runner.run(["systemctl", "disable", "--now", f"{base}.automount"], check=False)
    ctx.runner.run(["systemctl", "stop", f"{base}.mount"], check=False)


# --- actions ------------------------------------------------------------------


@action("remotes.list", mutating=False)
def remotes_list(ctx: Context):
    """Remote shares with their mount state; never the password."""
    return {"remotes": [{**r, "path": str(mountpoint(ctx, r["name"])),
                         "state": mount_state(ctx, r["name"]),
                         "has_password": cred_file(ctx, r["name"]).exists()}
                        for r in load(ctx)]}


@action(
    "remotes.set",
    mutating=True,
    params={
        "name": Param(str, pattern=NAME_RE),
        "type": Param(str, choices=TYPES),
        "host": Param(str, pattern=HOST_RE),
        "share": Param(str),
        "username": Param(str, required=False, default=""),
        "password": Param(str, required=False, default=None, pattern=PASSWORD_RE),
        "readonly": Param(bool, required=False, default=False),
    },
)
def remotes_set(ctx: Context, name: str, type: str, host: str, share: str, username: str,
                password: str | None, readonly: bool):
    """Add or change a remote share. It is test-mounted before anything is saved.

    password None keeps the saved one; SMB without username mounts as guest.
    """
    share_re = SMB_SHARE_RE if type == "smb" else NFS_PATH_RE
    if not share_re.match(share) or ".." in share.split("/"):
        raise AgentError(INVALID_PARAMS, "'share' is not a valid "
                         + ("SMB share name" if type == "smb" else "NFS export path"))
    if type == "nfs":
        username, password = "", None
    elif username and not SMB_USER_RE.match(username):
        raise AgentError(INVALID_PARAMS, "'username' contains characters that are not allowed")
    r = {"name": name, "type": type, "host": host, "share": share, "username": username,
         "readonly": readonly}
    test_mount(ctx, r, password)

    others = [x for x in load(ctx) if x["name"] != name]
    stop_units(ctx, name)
    cred = cred_file(ctx, name)
    if type == "smb" and username:
        if password is not None:
            write_cred(cred, username, password)
        else:
            # Same password, maybe a new user name.
            pw = next((ln[9:] for ln in cred.read_text().splitlines()
                       if ln.startswith("password=")), "")
            write_cred(cred, username, pw)
    else:
        cred.unlink(missing_ok=True)
    base = unit_base(ctx, name)
    write_file(unit_dir(ctx) / f"{base}.mount", render_mount(ctx, r))
    write_file(unit_dir(ctx) / f"{base}.automount", render_automount(ctx, r))
    mountpoint(ctx, name).mkdir(parents=True, exist_ok=True)
    save(ctx, others + [r])
    ctx.runner.run(["systemctl", "daemon-reload"])
    ctx.runner.run(["systemctl", "enable", "--now", f"{base}.automount"])
    return {**r, "path": str(mountpoint(ctx, name))}


@action(
    "remotes.remove",
    mutating=True,
    params={"name": Param(str, pattern=NAME_RE), "force": Param(bool, required=False,
                                                                 default=False)},
)
def remotes_remove(ctx: Context, name: str, force: bool):
    """Unmount and forget a remote share. Files on the other device stay."""
    remotes = load(ctx)
    if not any(r["name"] == name for r in remotes):
        raise AgentError(FAILED, f"no remote share '{name}'")
    used = apps_using(ctx, name)
    if used and not force:
        raise AgentError(FAILED, f"used by apps: {', '.join(used)}; remove with --force")
    stop_units(ctx, name)
    base = unit_base(ctx, name)
    for suffix in ("mount", "automount"):
        (unit_dir(ctx) / f"{base}.{suffix}").unlink(missing_ok=True)
    cred_file(ctx, name).unlink(missing_ok=True)
    save(ctx, [r for r in remotes if r["name"] != name])
    ctx.runner.run(["systemctl", "daemon-reload"])
    mp = mountpoint(ctx, name)
    # Only an empty directory; never anything that is still mounted.
    if mp.is_dir() and not os.path.ismount(mp):
        with contextlib.suppress(OSError):
            mp.rmdir()
    return {"name": name}
