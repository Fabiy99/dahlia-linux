"""SMB and NFS shares on /mnt/user and the SMB users.

Dahlia owns /etc/samba/smb.conf: it is generated from /etc/dahlia/shares.json
on every change. Shares are directories directly under /mnt/user, so they
span cache and data disks like the apps' shares do.

SMB users are system users without login or home, in the groups dahlia-smb
(marks them as managed here) and dahlia (group of the share directories,
shared with the apps). Their password lives only in Samba's passdb.

NFS: a public or secure share can also be exported over NFSv4 (read-write
or read-only) to local networks, the same ones the firewall lets in. NFS
has no login without Kerberos, so private shares are never exported. All
clients are mapped to nobody:dahlia (all_squash), like SMB guests. Exports
live in /etc/exports.d/dahlia.exports; NFSv3 is off (/etc/nfs.conf.d/dahlia.conf),
so only 2049/tcp is needed. nfs-server runs only while an export exists.

Recycle bin: a share with recycle_days > 0 moves files deleted over SMB to
<share>/.recycle (vfs_recycle, folder tree kept, access time set to the
deletion). dahlia-recycle.timer deletes files older than that many days
once a day; shares.empty_recycle empties it at once. NFS deletes are final.
"""

import argparse
import json
import os
import re
import stat
import sys
import time
import zlib
from pathlib import Path

from .actions import Context, Param, action
from .protocol import FAILED, INVALID_PARAMS, AgentError
from .settings import read_json, write_file

SMB_GROUP = "dahlia-smb"
DATA_GROUP = "dahlia"
SHARE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
USER_RE = re.compile(r"^[a-z][a-z0-9_-]{0,31}$")
# Printable, no line breaks: smbpasswd reads it line by line from stdin.
PASSWORD_RE = re.compile(r"^[^\x00-\x1f\x7f]{8,128}$")
COMMENT_RE = re.compile(r"^[^\x00-\x1f\x7f\[\]=\\]{0,80}$")
SECURITY = ("public", "secure", "private")
ACCESS = ("rw", "ro")
# Upper bound for the Time Machine size limit, in GB.
MAX_TM_SIZE = 1_000_000
NOBODY = 65534
# Names Samba or Windows treat specially.
RESERVED_SHARES = {"global", "homes", "printers", "print$", "ipc$"}
RECYCLE_DIR = ".recycle"
MAX_RECYCLE_DAYS = 365


def shares_file(ctx: Context) -> Path:
    return ctx.etc / "dahlia/shares.json"


def smb_conf(ctx: Context) -> Path:
    return ctx.etc / "samba/smb.conf"


def avahi_service(ctx: Context) -> Path:
    return ctx.etc / "avahi/services/dahlia-smb.service"


def exports_file(ctx: Context) -> Path:
    return ctx.etc / "exports.d/dahlia.exports"


def load_shares(ctx: Context) -> list[dict]:
    data = read_json(shares_file(ctx), {})
    shares = data.get("shares") if isinstance(data.get("shares"), list) else []
    out = []
    for s in shares:
        if not isinstance(s, dict) or not SHARE_RE.match(str(s.get("name", ""))):
            continue
        users = s.get("users") if isinstance(s.get("users"), dict) else {}
        security = s.get("security") if s.get("security") in SECURITY else "private"
        size = s.get("time_machine_size")
        out.append({
            "name": s["name"],
            "comment": s.get("comment") if isinstance(s.get("comment"), str)
            and COMMENT_RE.match(s["comment"]) else "",
            "security": security,
            "users": {u: a for u, a in users.items() if USER_RE.match(str(u)) and a in ACCESS},
            "time_machine": s.get("time_machine") is True,
            "time_machine_size": size if type(size) is int and 0 <= size <= MAX_TM_SIZE else 0,
            "nfs": s.get("nfs") is True and security != "private",
            "recycle_days": recycle if type(recycle := s.get("recycle_days")) is int
            and 0 <= recycle <= MAX_RECYCLE_DAYS else 0,
        })
    return out


def save_shares(ctx: Context, shares: list[dict]) -> None:
    shares = sorted(shares, key=lambda s: s["name"].lower())
    write_file(shares_file(ctx), json.dumps({"shares": shares}, indent=2) + "\n")


def smb_users(ctx: Context) -> list[str]:
    proc = ctx.runner.run(["getent", "group", SMB_GROUP], check=False)
    if proc.returncode != 0:
        return []
    members = proc.stdout.strip().split(":")[-1]
    return sorted(m for m in members.split(",") if m)


# --- smb.conf -----------------------------------------------------------------

GLOBAL = """\
# Generated by dahlia-agent from /etc/dahlia/shares.json. Changes here are overwritten.
[global]
   server string = Dahlia
   workgroup = WORKGROUP
   server role = standalone server
   server min protocol = SMB2_10
   map to guest = Bad User
   load printers = no
   printing = bsd
   printcap name = /dev/null
   disable spoolss = yes
   logging = file
   log file = /var/log/samba/log.%m
   max log size = 1000
   unix password sync = no
   usershare max shares = 0
   # macOS: Finder metadata, Time Machine.
   vfs objects = catia fruit streams_xattr
   fruit:metadata = stream
   fruit:model = MacSamba
   fruit:posix_rename = yes
   fruit:veto_appledouble = no
   fruit:wipe_intentionally_left_blank_rfork = yes
   fruit:delete_empty_adfiles = yes
"""


def render_share(pool: Path, s: dict) -> str:
    rw = sorted(u for u, a in s["users"].items() if a == "rw")
    lines = [
        f"[{s['name']}]",
        f"   path = {pool / s['name']}",
        f"   comment = {s['comment']}" if s["comment"] else None,
        "   browseable = yes",
        # Same group and modes as the share directories the apps create.
        f"   force group = {DATA_GROUP}",
        "   create mask = 0664",
        "   directory mask = 2775",
    ]
    if s["security"] == "public":
        lines += ["   guest ok = yes", "   read only = no"]
    elif s["security"] == "secure":
        lines += ["   guest ok = yes", "   read only = yes"]
    else:
        lines += ["   guest ok = no", "   read only = yes",
                  f"   valid users = {' '.join(sorted(s['users'])) or 'nobody-dahlia'}"]
    if s["security"] != "public":
        lines.append(f"   write list = {' '.join(rw)}" if rw else None)
    if s.get("time_machine"):
        lines.append("   fruit:time machine = yes")
        if s.get("time_machine_size"):
            lines.append(f"   fruit:time machine max size = {s['time_machine_size']}G")
    if s.get("recycle_days"):
        lines += [
            # A share's vfs objects replace the global list, so repeat it.
            "   vfs objects = catia fruit streams_xattr recycle",
            f"   recycle:repository = {RECYCLE_DIR}",
            "   recycle:keeptree = yes",
            "   recycle:versions = yes",
            "   recycle:touch = yes",
            "   recycle:directory_mode = 2775",
            "   recycle:exclude = *.tmp,*.temp,~$*,.DS_Store,Thumbs.db",
            f"   recycle:exclude_dir = {RECYCLE_DIR},.TemporaryItems",
        ]
    return "\n".join(ln for ln in lines if ln) + "\n"


def render_conf(pool: Path, shares: list[dict]) -> str:
    return GLOBAL + "".join("\n" + render_share(pool, s) for s in shares)


def render_avahi(shares: list[dict]) -> str:
    """mDNS records so macOS lists the server and Time Machine targets."""
    records = [
        "  <service>\n    <type>_smb._tcp</type>\n    <port>445</port>\n  </service>",
        "  <service>\n    <type>_device-info._tcp</type>\n    <port>0</port>\n"
        "    <txt-record>model=RackMac</txt-record>\n  </service>",
    ]
    tm = [s["name"] for s in shares if s.get("time_machine")]
    if tm:
        txt = "".join(f"\n    <txt-record>dk{i}=adVN={n},adVF=0x82</txt-record>"
                      for i, n in enumerate(tm))
        records.append("  <service>\n    <type>_adisk._tcp</type>\n    <port>9</port>\n"
                       f"    <txt-record>sys=waMa=0,adVF=0x100</txt-record>{txt}\n  </service>")
    return ('<?xml version="1.0" standalone="no"?>\n'
            '<!DOCTYPE service-group SYSTEM "avahi-service.dtd">\n'
            "<!-- Generated by dahlia-agent. -->\n<service-group>\n"
            '  <name replace-wildcards="yes">%h</name>\n'
            + "\n".join(records) + "\n</service-group>\n")


# --- NFS ----------------------------------------------------------------------


def nfs_fsid(name: str) -> int:
    """Stable export id: mergerfs (FUSE) has no device number nfsd could use."""
    return zlib.crc32(name.encode()) % 0x7FFFFFFF + 1


def nfs_clients(ctx: Context) -> list[str]:
    """Private ranges plus the extra networks of the firewall settings."""
    from .firewall import PRIVATE4, PRIVATE6, load_settings

    extra = load_settings(ctx.etc / "dahlia/firewall.json").get("networks", [])
    return list(PRIVATE4) + list(PRIVATE6) + [n for n in extra if n not in PRIVATE4 + PRIVATE6]


def nfs_exports(shares: list[dict]) -> list[dict]:
    return [s for s in shares if s.get("nfs") and s["security"] != "private"]


def render_exports(pool: Path, shares: list[dict], clients: list[str], gid: int) -> str:
    lines = ["# Generated by dahlia-agent from /etc/dahlia/shares.json. "
             "Changes here are overwritten."]
    for s in nfs_exports(shares):
        mode = "rw" if s["security"] == "public" else "ro"
        opts = (f"{mode},sync,no_subtree_check,all_squash,anonuid={NOBODY},anongid={gid},"
                f"fsid={nfs_fsid(s['name'])},sec=sys")
        lines.append(f"{pool / s['name']} " + " ".join(f"{c}({opts})" for c in clients))
    return "\n".join(lines) + "\n"


def apply_nfs(ctx: Context, shares: list[dict]) -> None:
    """Write the exports and start or stop nfs-server."""
    path = exports_file(ctx)
    if nfs_exports(shares):
        write_file(path, render_exports(ctx.pool, shares, nfs_clients(ctx), data_gid(ctx)))
        ctx.runner.run(["systemctl", "enable", "--now", "nfs-server.service"])
        ctx.runner.run(["exportfs", "-ra"])
    elif path.exists():
        path.unlink()
        ctx.runner.run(["exportfs", "-ra"], check=False)
        ctx.runner.run(["systemctl", "disable", "--now", "nfs-server.service"], check=False)


def apply(ctx: Context, shares: list[dict]) -> None:
    """Write smb.conf, check it with testparm, then (re)start or stop Samba."""
    conf = smb_conf(ctx)
    orig = conf.with_name("smb.conf.dahlia-orig")
    if conf.exists() and not orig.exists():
        orig.write_text(conf.read_text())
    new = conf.with_name("smb.conf.dahlia-new")
    new.parent.mkdir(parents=True, exist_ok=True)
    new.write_text(render_conf(ctx.pool, shares))
    proc = ctx.runner.run(["testparm", "-s", str(new)], check=False)
    if proc.returncode != 0:
        new.unlink(missing_ok=True)
        lines = [ln for ln in (proc.stderr or "").splitlines() if ln.strip()]
        raise AgentError(FAILED, f"testparm: {lines[-1] if lines else 'invalid configuration'}")
    new.chmod(0o644)
    new.replace(conf)
    if shares:
        write_file(avahi_service(ctx), render_avahi(shares))
        ctx.runner.run(["systemctl", "enable", "--now", "smbd.service"])
        ctx.runner.run(["systemctl", "reload-or-restart", "smbd.service"])
        ctx.runner.run(["systemctl", "enable", "--now", "wsdd.service"], check=False)
        # NetBIOS is not needed; Windows finds the server through WS-Discovery (wsdd).
        ctx.runner.run(["systemctl", "disable", "--now", "nmbd.service"], check=False)
    else:
        avahi_service(ctx).unlink(missing_ok=True)
        ctx.runner.run(["systemctl", "disable", "--now", "smbd.service", "nmbd.service"],
                       check=False)
        ctx.runner.run(["systemctl", "disable", "--now", "wsdd.service"], check=False)
    apply_nfs(ctx, shares)


# --- actions ------------------------------------------------------------------


@action("shares.list", mutating=False)
def shares_list(ctx: Context):
    """Shares, SMB users, whether /mnt/user is mounted and Samba/nfsd run."""
    shares = [{**s, "exists": (ctx.pool / s["name"]).is_dir()} for s in load_shares(ctx)]
    active = ctx.runner.run(["systemctl", "is-active", "smbd.service"], check=False)
    nfs = ctx.runner.run(["systemctl", "is-active", "nfs-server.service"], check=False)
    return {
        "shares": shares,
        "users": smb_users(ctx),
        "pool_mounted": os.path.ismount(ctx.pool),
        "running": active.stdout.strip() == "active",
        "nfs_running": nfs.stdout.strip() == "active",
    }


@action(
    "shares.set",
    mutating=True,
    params={
        "name": Param(str, pattern=SHARE_RE),
        "comment": Param(str, required=False, default="", pattern=COMMENT_RE),
        "security": Param(str, choices=SECURITY),
        "users": Param(dict, required=False, default=None),
        "time_machine": Param(bool, required=False, default=False),
        "time_machine_size": Param(int, required=False, default=0, minimum=0,
                                   maximum=MAX_TM_SIZE),
        "nfs": Param(bool, required=False, default=False),
        "recycle_days": Param(int, required=False, default=0, minimum=0,
                              maximum=MAX_RECYCLE_DAYS),
    },
)
def shares_set(ctx: Context, name: str, comment: str, security: str, users: dict | None,
               time_machine: bool, time_machine_size: int, nfs: bool, recycle_days: int):
    """Create or change a share of /mnt/user/<name>. Data is never touched."""
    if name.lower() in RESERVED_SHARES:
        raise AgentError(INVALID_PARAMS, f"'{name}' is a reserved name")
    known = set(smb_users(ctx))
    access = {}
    for user, mode in (users or {}).items():
        if user not in known:
            raise AgentError(INVALID_PARAMS, f"unknown SMB user '{user}'")
        if mode not in ACCESS:
            raise AgentError(INVALID_PARAMS, f"'users.{user}' must be rw or ro")
        access[user] = mode
    if security == "private" and not access:
        raise AgentError(INVALID_PARAMS, "a private share needs at least one user")
    if security == "private" and nfs:
        raise AgentError(INVALID_PARAMS, "NFS has no login; export only public or secure shares")
    shares = [s for s in load_shares(ctx) if s["name"].lower() != name.lower()]
    path = ctx.pool / name
    if not path.is_dir():
        if not os.path.ismount(ctx.pool):
            raise AgentError(FAILED, f"{ctx.pool} is not mounted; add a data disk first")
        path.mkdir(mode=0o2775)
        os.chown(path, 0, data_gid(ctx))
    share = {"name": name, "comment": comment, "security": security, "users": access,
             "time_machine": time_machine,
             "time_machine_size": time_machine_size if time_machine else 0, "nfs": nfs,
             "recycle_days": recycle_days}
    shares.append(share)
    apply(ctx, shares)
    save_shares(ctx, shares)
    reload_firewall(ctx)
    return share


# --- recycle bin ------------------------------------------------------------------


def recycle_path(ctx: Context, name: str) -> Path | None:
    """<pool>/<share>/.recycle if it is a real directory (no symlink), else None."""
    path = ctx.pool / name / RECYCLE_DIR
    try:
        st = path.lstat()
    except OSError:
        return None
    return path if stat.S_ISDIR(st.st_mode) else None


def clean_tree(root: Path, older_than: float | None) -> tuple[int, int]:
    """Delete files (all, or last accessed before older_than) and empty folders
    below root, without following symlinks. Returns (files, bytes)."""
    files = size = 0
    for dirpath, dirnames, filenames in os.walk(root, topdown=False):
        for f in filenames:
            p = os.path.join(dirpath, f)
            try:
                st = os.lstat(p)
                if older_than is None or st.st_atime < older_than:
                    os.unlink(p)
                    files += 1
                    size += st.st_size if stat.S_ISREG(st.st_mode) else 0
            except OSError:
                continue
        for d in dirnames:
            p = os.path.join(dirpath, d)
            try:
                if os.path.islink(p):
                    if older_than is None:
                        os.unlink(p)
                else:
                    os.rmdir(p)  # only succeeds when empty
            except OSError:
                continue
    return files, size


def clean_recycle(ctx: Context) -> dict[str, dict]:
    """Daily: drop what lies in a recycle bin longer than the share allows."""
    out = {}
    for s in load_shares(ctx):
        path = recycle_path(ctx, s["name"])
        if not s["recycle_days"] or path is None:
            continue
        files, size = clean_tree(path, ctx.clock() - s["recycle_days"] * 86400)
        out[s["name"]] = {"files": files, "bytes": size}
    return out


@action("shares.empty_recycle", mutating=True, params={"name": Param(str, pattern=SHARE_RE)})
def shares_empty_recycle(ctx: Context, name: str):
    """Empty the recycle bin of a share now."""
    if not any(s["name"] == name for s in load_shares(ctx)):
        raise AgentError(INVALID_PARAMS, f"no share '{name}'")
    path = recycle_path(ctx, name)
    if path is None:
        return {"name": name, "files": 0, "bytes": 0}
    files, size = clean_tree(path, None)
    return {"name": name, "files": files, "bytes": size}


def recycle_main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="dahlia-recycle",
                                     description="Clean the SMB recycle bins.")
    parser.add_argument("command", choices=("clean",))
    parser.parse_args(argv)
    for name, r in clean_recycle(Context(clock=time.time)).items():
        print(f"{name}: {r['files']} files, {r['bytes']} bytes removed", file=sys.stderr)
    return 0


def reload_firewall(ctx: Context) -> None:
    """SMB, WS-Discovery and NFS ports are open only while shares use them."""
    from .firewall import apply_quietly
    from .network import firewall_of

    apply_quietly(firewall_of(ctx))


def data_gid(ctx: Context) -> int:
    proc = ctx.runner.run(["getent", "group", DATA_GROUP])
    return int(proc.stdout.split(":")[2])


@action("shares.remove", mutating=True, params={"name": Param(str, pattern=SHARE_RE)})
def shares_remove(ctx: Context, name: str):
    """Stop sharing a directory. The files stay on the array."""
    shares = load_shares(ctx)
    rest = [s for s in shares if s["name"] != name]
    if len(rest) == len(shares):
        raise AgentError(FAILED, f"no share '{name}'")
    apply(ctx, rest)
    save_shares(ctx, rest)
    reload_firewall(ctx)
    return {"name": name}


def set_password(ctx: Context, user: str, password: str, add: bool) -> None:
    cmd = ["smbpasswd", "-s", "-a", user] if add else ["smbpasswd", "-s", user]
    ctx.runner.run(cmd, input=f"{password}\n{password}\n")


@action(
    "shares.user_add",
    mutating=True,
    params={"name": Param(str, pattern=USER_RE), "password": Param(str, pattern=PASSWORD_RE)},
)
def shares_user_add(ctx: Context, name: str, password: str):
    """Create an SMB user (no shell, no home) with a password."""
    if ctx.runner.run(["getent", "passwd", name], check=False).returncode == 0:
        raise AgentError(FAILED, f"user '{name}' already exists")
    ctx.runner.run(["useradd", "--system", "--no-create-home", "--home-dir", "/nonexistent",
                    "--shell", "/usr/sbin/nologin", "--groups", f"{DATA_GROUP},{SMB_GROUP}",
                    name])
    try:
        set_password(ctx, name, password, add=True)
    except AgentError:
        ctx.runner.run(["userdel", name], check=False)
        raise
    return {"name": name}


def managed_user(ctx: Context, name: str) -> None:
    if name not in smb_users(ctx):
        raise AgentError(FAILED, f"'{name}' is not an SMB user of Dahlia")


@action(
    "shares.user_password",
    mutating=True,
    params={"name": Param(str, pattern=USER_RE), "password": Param(str, pattern=PASSWORD_RE)},
)
def shares_user_password(ctx: Context, name: str, password: str):
    """Set a new password for an SMB user."""
    managed_user(ctx, name)
    set_password(ctx, name, password, add=False)
    return {"name": name}


@action("shares.user_remove", mutating=True, params={"name": Param(str, pattern=USER_RE)})
def shares_user_remove(ctx: Context, name: str):
    """Delete an SMB user and drop it from all shares. Files keep their owner id."""
    managed_user(ctx, name)
    shares = load_shares(ctx)
    for s in shares:
        s["users"].pop(name, None)
    # A private share without users is left with no access at all.
    apply(ctx, shares)
    save_shares(ctx, shares)
    ctx.runner.run(["smbpasswd", "-x", name], check=False)
    ctx.runner.run(["userdel", name])
    return {"name": name}
