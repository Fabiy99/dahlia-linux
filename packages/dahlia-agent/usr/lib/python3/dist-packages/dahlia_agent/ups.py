"""UPS through NUT: a USB UPS on this server or a NUT server in the network.

Dahlia writes the NUT configuration from /etc/dahlia/ups.json. upsmon calls
dahlia-notify ups-event for every power event; on battery a transient timer
powers the server off after the configured minutes, back on line stops it.
Without a timer upsmon shuts down when the UPS reports a low battery.
"""

import json
import os
import re
import secrets
from pathlib import Path

from .actions import Context, Param, action
from .protocol import INVALID_PARAMS, AgentError
from .settings import read_json, write_file

MODES = ("off", "usb", "remote")
SHUTDOWN_UNIT = "dahlia-ups-shutdown"
HOST_RE = re.compile(r"^$|^[A-Za-z0-9]([A-Za-z0-9.:-]{0,252}[A-Za-z0-9])?$")
NAME_RE = re.compile(r"^[A-Za-z0-9_.-]{1,32}$")
# upsmon.conf has no quoting worth relying on: no spaces, no quotes.
CRED_RE = re.compile(r"^$|^[A-Za-z0-9._@%+=:,/-]{1,64}$")
DEFAULTS = {"mode": "off", "host": "", "port": 3493, "name": "ups", "user": "",
            "password": "", "shutdown_minutes": 0}
# NOTIFYTYPE -> (level, English text for the notification).
EVENTS = {
    "ONBATT": ("warning", "UPS on battery"),
    "ONLINE": ("info", "UPS back on mains power"),
    "LOWBATT": ("critical", "UPS battery low, the server shuts down"),
    "FSD": ("critical", "UPS forces shutdown"),
    "SHUTDOWN": ("critical", "Server shuts down because of the UPS"),
    "COMMBAD": ("warning", "Lost connection to the UPS"),
    "NOCOMM": ("warning", "UPS not reachable"),
    "COMMOK": ("info", "Connection to the UPS restored"),
    "REPLBATT": ("warning", "UPS battery needs replacing"),
}
NOTIFY_FLAGS = tuple(EVENTS)
STATUS_KEYS = ("device.model", "device.mfr", "ups.status", "battery.charge", "battery.runtime",
               "ups.load", "input.voltage", "ups.realpower.nominal")


def config_file(ctx: Context) -> Path:
    return ctx.etc / "dahlia/ups.json"


def load_config(ctx: Context) -> dict:
    data = read_json(config_file(ctx), {})
    return {k: data.get(k, v) if type(data.get(k, v)) is type(v) else v
            for k, v in DEFAULTS.items()}


def event_type() -> str:
    return os.environ.get("NOTIFYTYPE", "")


# --- NUT files ----------------------------------------------------------------


def monitor_line(cfg: dict, mon_password: str) -> str:
    if cfg["mode"] == "usb":
        return f"MONITOR {cfg['name']}@localhost 1 dahlia-mon {mon_password} primary"
    return (f"MONITOR {cfg['name']}@{cfg['host']}:{cfg['port']} 1 "
            f"{cfg['user']} {cfg['password']} secondary")


def render_upsmon(cfg: dict, mon_password: str) -> str:
    lines = [
        "# Generated by dahlia-agent from /etc/dahlia/ups.json.",
        monitor_line(cfg, mon_password),
        "MINSUPPLIES 1",
        'SHUTDOWNCMD "/sbin/shutdown -h +0"',
        # Root, so the notification can read the channel secrets.
        "RUN_AS_USER root",
        "NOTIFYCMD /usr/lib/dahlia/ups-notify.sh",
        "POWERDOWNFLAG /etc/killpower",
        "POLLFREQ 5",
        "POLLFREQALERT 5",
        "DEADTIME 25",
    ]
    lines += [f"NOTIFYFLAG {f} SYSLOG+EXEC" for f in NOTIFY_FLAGS]
    return "\n".join(lines) + "\n"


def write_nut(ctx: Context, cfg: dict) -> None:
    nut = ctx.etc / "nut"
    mode = {"off": "none", "usb": "standalone", "remote": "netclient"}[cfg["mode"]]
    write_file(nut / "nut.conf", f"# Generated by dahlia-agent.\nMODE={mode}\n")
    if cfg["mode"] == "off":
        return
    users = nut / "upsd.users"
    mon_password = ""
    if cfg["mode"] == "usb":
        old = users.read_text() if users.exists() else ""
        m = re.search(r"password = (\S+)", old)
        mon_password = m.group(1) if m and "[dahlia-mon]" in old else secrets.token_hex(16)
        write_file(nut / "ups.conf",
                   f"# Generated by dahlia-agent.\n[{cfg['name']}]\n"
                   "    driver = usbhid-ups\n    port = auto\n    desc = \"Dahlia UPS\"\n")
        write_file(nut / "upsd.conf",
                   "# Generated by dahlia-agent. Local clients only.\n"
                   "LISTEN 127.0.0.1 3493\nLISTEN ::1 3493\n")
        write_file(users, f"# Generated by dahlia-agent.\n[dahlia-mon]\n"
                          f"    password = {mon_password}\n    upsmon primary\n", 0o640)
    write_file(nut / "upsmon.conf", render_upsmon(cfg, mon_password), 0o640)
    for f in ("upsd.users", "upsmon.conf"):
        if (nut / f).exists():
            ctx.runner.run(["chown", "root:nut", str(nut / f)], check=False)


def apply_services(ctx: Context, mode: str) -> None:
    run = ctx.runner.run
    if mode == "off":
        run(["systemctl", "disable", "--now", "nut-monitor.service", "nut-server.service",
             "nut-driver.target"], check=False)
        run(["systemctl", "stop", f"{SHUTDOWN_UNIT}.timer"], check=False)
        return
    if mode == "usb":
        # NUT 2.8 creates nut-driver@<name> from ups.conf.
        run(["systemctl", "restart", "nut-driver-enumerator.service"], check=False)
        run(["systemctl", "enable", "nut-driver.target", "nut-server.service"], check=False)
        run(["systemctl", "restart", "nut-driver.target", "nut-server.service"], check=False)
    else:
        run(["systemctl", "disable", "--now", "nut-server.service", "nut-driver.target"],
            check=False)
    run(["systemctl", "enable", "nut-monitor.service"])
    run(["systemctl", "restart", "nut-monitor.service"])


def read_status(ctx: Context, cfg: dict) -> dict | None:
    if cfg["mode"] == "off":
        return None
    target = (f"{cfg['name']}@localhost" if cfg["mode"] == "usb"
              else f"{cfg['name']}@{cfg['host']}:{cfg['port']}")
    proc = ctx.runner.run(["upsc", target], timeout=15, check=False)
    if proc.returncode != 0:
        lines = (proc.stderr or "").strip().splitlines()
        return {"reachable": False, "error": lines[-1] if lines else "upsc failed"}
    values = {}
    for line in proc.stdout.splitlines():
        key, sep, value = line.partition(": ")
        if sep and key in STATUS_KEYS:
            values[key] = value.strip()
    flags = values.get("ups.status", "").split()

    def num(key):
        try:
            return float(values[key])
        except (KeyError, ValueError):
            return None

    return {
        "reachable": True,
        "model": " ".join(v for v in (values.get("device.mfr"), values.get("device.model")) if v),
        "flags": flags,
        "on_battery": "OB" in flags,
        "low_battery": "LB" in flags,
        "charge": num("battery.charge"),
        "runtime": num("battery.runtime"),
        "load": num("ups.load"),
        "input_voltage": num("input.voltage"),
    }


# --- events -------------------------------------------------------------------


def handle_event(ctx: Context, kind: str, message: str) -> None:
    from . import notify

    cfg = load_config(ctx)
    level, text = EVENTS.get(kind, ("warning", f"UPS event {kind or 'unknown'}"))
    detail = message or text
    if kind == "ONBATT" and cfg["shutdown_minutes"] > 0:
        ctx.runner.run(["systemd-run", f"--unit={SHUTDOWN_UNIT}",
                        f"--on-active={cfg['shutdown_minutes']}min",
                        "--timer-property=AccuracySec=10s", "systemctl", "poweroff"], check=False)
        detail += f" The server powers off in {cfg['shutdown_minutes']} minutes" \
                  " unless the power comes back."
    elif kind == "ONLINE":
        ctx.runner.run(["systemctl", "stop", f"{SHUTDOWN_UNIT}.timer"], check=False)
    notify.send(ctx, level, text, detail, "ups")


# --- actions ------------------------------------------------------------------


@action("ups.get", mutating=False)
def ups_get(ctx: Context):
    """UPS settings (without password) and the current state."""
    cfg = load_config(ctx)
    status = read_status(ctx, cfg)
    password_set = bool(cfg.pop("password"))
    return {**cfg, "password_set": password_set, "status": status}


@action(
    "ups.set",
    mutating=True,
    params={
        "mode": Param(str, choices=MODES),
        "host": Param(str, required=False, default="", pattern=HOST_RE),
        "port": Param(int, required=False, default=3493, minimum=1, maximum=65535),
        "name": Param(str, required=False, default="ups", pattern=NAME_RE),
        "user": Param(str, required=False, default="", pattern=CRED_RE),
        "password": Param(str, required=False, default="", pattern=CRED_RE),
        "shutdown_minutes": Param(int, required=False, default=0, minimum=0, maximum=120),
    },
)
def ups_set(ctx: Context, mode: str, host: str, port: int, name: str, user: str, password: str,
            shutdown_minutes: int):
    """Set up NUT for a USB UPS or a NUT server, or switch it off."""
    old = load_config(ctx)
    if mode == "remote":
        password = password or old["password"]
        missing = [k for k, v in (("host", host), ("user", user), ("password", password)) if not v]
        if missing:
            raise AgentError(INVALID_PARAMS, f"missing: {', '.join(missing)}")
    cfg = {"mode": mode, "host": host, "port": port, "name": name, "user": user,
           "password": password, "shutdown_minutes": shutdown_minutes}
    write_nut(ctx, cfg)
    write_file(config_file(ctx), json.dumps(cfg, indent=2) + "\n", 0o600)
    apply_services(ctx, mode)
    out = dict(cfg)
    out["password_set"] = bool(out.pop("password"))
    return out
