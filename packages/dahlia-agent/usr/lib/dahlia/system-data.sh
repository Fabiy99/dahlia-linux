#!/bin/bash
# Set up /srv/dahlia, where apps keep their data on the system SSD.
#
# On a Btrfs root it is the top-level subvolume @dahlia, mounted by a
# systemd mount unit. It is not part of the snapper snapshots of /, so a
# rollback neither takes app data back nor loses it. On other root
# filesystems it is a plain directory. Runs once; an existing unit, a
# mounted target or a non-empty directory is left alone.
#
# Environment (tests): DAHLIA_SYSTEM_DATA (target), DAHLIA_SYSTEM_ROOT
# (mount point of the root fs), DAHLIA_UNIT_DIR, DAHLIA_NO_SYSTEMCTL=1.
set -euo pipefail

target="${DAHLIA_SYSTEM_DATA:-/srv/dahlia}"
root="${DAHLIA_SYSTEM_ROOT:-/}"
unit_dir="${DAHLIA_UNIT_DIR:-/etc/systemd/system}"
unit="$(systemd-escape --path --suffix=mount "$target")"

if [ -e "$unit_dir/$unit" ] || mountpoint -q "$target" 2>/dev/null; then
    exit 0
fi
if [ "$(findmnt -no FSTYPE --mountpoint "$root")" != "btrfs" ]; then
    mkdir -p "$target"
    chmod 0755 "$target"
    exit 0
fi
if [ -d "$target" ] && [ -n "$(ls -A "$target")" ]; then
    echo "dahlia-agent: $target is not empty, kept as a plain directory" >&2
    exit 0
fi

# SOURCE looks like /dev/sda2[/@rootfs]; the subvolume part is not a device.
dev="$(findmnt -no SOURCE --mountpoint "$root")"
dev="${dev%%\[*}"
uuid="$(findmnt -no UUID --mountpoint "$root")"
top="$(mktemp -d /run/dahlia-btrfs.XXXXXX)"
cleanup() {
    mountpoint -q "$top" && umount "$top"
    rmdir "$top"
}
trap cleanup EXIT
mount -t btrfs -o subvolid=5 "$dev" "$top"
if [ ! -d "$top/@dahlia" ]; then
    btrfs -q subvolume create "$top/@dahlia"
    chmod 0755 "$top/@dahlia"
fi

mkdir -p "$target" "$unit_dir"
cat > "$unit_dir/$unit" <<UNIT
# Generated by dahlia-agent (system-data.sh).
[Unit]
Description=Dahlia app data on the system SSD
Before=docker.service dahlia-apps.service

[Mount]
What=/dev/disk/by-uuid/$uuid
Where=$target
Type=btrfs
Options=subvol=@dahlia,noatime,nofail

[Install]
WantedBy=local-fs.target
UNIT

if [ "${DAHLIA_NO_SYSTEMCTL:-0}" != 1 ] && [ -d /run/systemd/system ]; then
    systemctl daemon-reload
    systemctl enable --now "$unit"
fi
