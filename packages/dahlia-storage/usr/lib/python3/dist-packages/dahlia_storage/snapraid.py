"""Generation and validation of /etc/snapraid.conf."""

from __future__ import annotations

import re

from .state import State

CONFIG_PATH = "/etc/snapraid.conf"
LOCAL_CONTENT = "/var/lib/snapraid/snapraid.content"

# Paths SnapRAID must never protect: they change constantly or are rebuilt.
EXCLUDES = [
    "*.tmp",
    "*.part",
    "/lost+found/",
    ".Trash-*/",
    ".recycle/",
    "/appdata/",
    "/.snapraid.content*",
    "*.dahlia-mover.tmp",
]

PARITY_PREFIXES = ["parity", "2-parity", "3-parity", "4-parity", "5-parity", "6-parity"]


class SnapraidError(ValueError):
    pass


def validate(state: State) -> list[str]:
    """Return human-readable problems; empty list means the layout is usable."""
    problems = []
    data = state.by_role("data")
    parity = state.by_role("parity")
    if not data:
        problems.append("no data disks")
    if not parity:
        problems.append("no parity disk")
    if len(parity) > len(PARITY_PREFIXES):
        problems.append(f"at most {len(PARITY_PREFIXES)} parity disks are supported")
    if data and parity:
        largest = max(d.size for d in data)
        for p in parity:
            if p.size < largest:
                problems.append(
                    f"parity {p.mountpoint} ({p.size} bytes) is smaller than the "
                    f"largest data disk ({largest} bytes)"
                )
    return problems


def render(state: State) -> str:
    problems = validate(state)
    if problems:
        raise SnapraidError("; ".join(problems))

    data = state.by_role("data")
    parity = state.by_role("parity")
    lines = [
        "# Generated by dahlia-disk from /etc/dahlia/storage.json. Do not edit.",
        "",
    ]
    for prefix, disk in zip(PARITY_PREFIXES, parity, strict=False):
        lines.append(f"{prefix} {disk.mountpoint}/snapraid.parity")
    lines.append("")
    # Content files: one on the system disk plus up to two data disks.
    lines.append(f"content {LOCAL_CONTENT}")
    for disk in data[:2]:
        lines.append(f"content {disk.mountpoint}/.snapraid.content")
    lines.append("")
    for disk in data:
        lines.append(f"data d{disk.index} {disk.mountpoint}/")
    lines.append("")
    for pattern in EXCLUDES:
        lines.append(f"exclude {pattern}")
    lines.append("")
    lines.append("autosave 500")
    lines.append("")
    return "\n".join(lines)


DIFF_LINE = re.compile(r"^\s*(\d+)\s+(equal|added|removed|updated|moved|copied|restored)\s*$")


def parse_diff(output: str) -> dict[str, int]:
    """Counts from the summary at the end of `snapraid diff`."""
    counts = {}
    for line in output.splitlines():
        m = DIFF_LINE.match(line)
        if m:
            counts[m.group(2)] = int(m.group(1))
    if "removed" not in counts:
        raise SnapraidError("could not read the summary of snapraid diff")
    return counts


def parse_status(log: str) -> dict:
    """Facts from the tagged log of `snapraid -l ">&1" status`.

    files/disks: what the parity covers. unsynced: blocks of an interrupted
    sync. unscrubbed: blocks never checked by a scrub. bad: blocks a scrub
    found broken ("snapraid -e fix" repairs them). scrub_oldest/newest: Unix
    time of the oldest and newest check or sync of any block.
    """
    disks: dict[str, dict] = {}
    facts: dict[str, int] = {}
    times: list[int] = []
    for line in log.splitlines():
        parts = line.split(":")
        if parts[0] == "info_time" and len(parts) >= 3 and parts[1].isdigit():
            times.append(int(parts[1]))
            continue
        if parts[0] != "summary" or len(parts) < 3:
            continue
        key = parts[1]
        if key in ("disk_file_count", "disk_file_size") and len(parts) == 4 and parts[3].isdigit():
            disks.setdefault(parts[2], {})["files" if key == "disk_file_count" else "size"] = \
                int(parts[3])
        elif key in ("file_count", "file_size", "has_unsynced", "has_unscrubbed",
                     "parity_block_count") and parts[2].isdigit():
            facts[key] = int(parts[2])
        elif key == "has_bad" and parts[2].isdigit():
            facts["has_bad"] = int(parts[2])
    if "has_bad" not in facts:
        raise SnapraidError("could not read the summary of snapraid status")
    return {
        "files": facts.get("file_count", sum(d.get("files", 0) for d in disks.values())),
        "size": facts.get("file_size", sum(d.get("size", 0) for d in disks.values())),
        "disks": disks,
        "blocks": facts.get("parity_block_count", 0),
        "unsynced": facts.get("has_unsynced", 0),
        "unscrubbed": facts.get("has_unscrubbed", 0),
        "bad": facts["has_bad"],
        "scrub_oldest": min(times) if times else None,
        "scrub_newest": max(times) if times else None,
    }
