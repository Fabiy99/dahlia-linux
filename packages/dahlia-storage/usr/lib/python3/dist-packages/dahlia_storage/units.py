"""Generation of systemd mount units for disks and mergerfs pools.

Disk units are pulled in by dahlia-storage.target with Wants=, never
Requires=. A missing or dead disk therefore only fails its own unit; the
system keeps booting (the same effect as `nofail` in fstab).
"""

from __future__ import annotations

from .state import Disk, State

UNIT_DIR = "/etc/systemd/system"
TARGET = "dahlia-storage.target"

STORAGE_POOL = "/mnt/storage"  # data disks only, mover target
USER_POOL = "/mnt/user"  # what apps and shares use

MOUNT_OPTIONS = {
    "ext4": "defaults,noatime",
    "xfs": "defaults,noatime",
    "btrfs": "defaults,noatime",
    # External only. UID/GID 1000 = group 'dahlia', so apps can read them.
    "ntfs": "uid=1000,gid=1000,umask=002,windows_names",
    "exfat": "uid=1000,gid=1000,umask=002",
}
MOUNT_TYPES = {"ntfs": "ntfs3"}


def escape_path(path: str) -> str:
    """systemd-escape --path, for the paths Dahlia generates."""
    parts = [p for p in path.strip("/").split("/") if p]
    escaped = []
    for part in parts:
        out = []
        for i, ch in enumerate(part):
            if ch.isascii() and (ch.isalnum() or ch == "_" or (ch == "." and i > 0)):
                out.append(ch)
            else:
                out.append("".join(f"\\x{b:02x}" for b in ch.encode()))
        escaped.append("".join(out))
    return "-".join(escaped)


def unit_name(mountpoint: str) -> str:
    return f"{escape_path(mountpoint)}.mount"


def disk_unit(disk: Disk) -> str:
    fstype = MOUNT_TYPES.get(disk.fstype, disk.fstype)
    label = {"data": "data disk", "parity": "parity disk", "external": "external disk"}[disk.role]
    return (
        "# Generated by dahlia-disk from /etc/dahlia/storage.json. Do not edit.\n"
        "[Unit]\n"
        f"Description=Dahlia {label} {disk.mountpoint}\n"
        "\n"
        "[Mount]\n"
        f"What=/dev/disk/by-uuid/{disk.uuid}\n"
        f"Where={disk.mountpoint}\n"
        f"Type={fstype}\n"
        f"Options={MOUNT_OPTIONS[disk.fstype]}\n"
        "TimeoutSec=60\n"
        "\n"
        "[Install]\n"
        f"WantedBy={TARGET}\n"
    )


def pool_branches(state: State, pool: str) -> list[str]:
    # The cache tier (/mnt/cache/shares first in /mnt/user) is added once
    # cache support lands; until then both pools span the data disks.
    return [d.mountpoint for d in state.by_role("data")]


def pool_options(state: State, pool: str) -> str:
    fsname = "dahlia-storage" if pool == STORAGE_POOL else "dahlia-user"
    return ",".join(
        [
            "allow_other",
            "cache.files=off",
            "dropcacheonclose=true",
            "category.create=mfs",
            "moveonenospc=true",
            f"minfreespace={state.settings.minfreespace}",
            "inodecalc=path-hash",
            "noforget",
            f"fsname={fsname}",
        ]
    )


def pool_unit(state: State, pool: str) -> str:
    branches = pool_branches(state, pool)
    deps = " ".join(unit_name(b) for b in branches)
    return (
        "# Generated by dahlia-disk from /etc/dahlia/storage.json. Do not edit.\n"
        "[Unit]\n"
        f"Description=Dahlia mergerfs pool {pool}\n"
        f"Wants={deps}\n"
        f"After={deps}\n"
        "\n"
        "[Mount]\n"
        f"What={':'.join(branches)}\n"
        f"Where={pool}\n"
        "Type=fuse.mergerfs\n"
        f"Options={pool_options(state, pool)}\n"
        "\n"
        "[Install]\n"
        f"WantedBy={TARGET}\n"
    )


def render_all(state: State) -> dict[str, str]:
    """Map of unit file name -> content for the whole layout."""
    units = {unit_name(d.mountpoint): disk_unit(d) for d in state.disks}
    if state.by_role("data"):
        for pool in (STORAGE_POOL, USER_POOL):
            units[unit_name(pool)] = pool_unit(state, pool)
    return units
