"""dahlia-disk: manage Dahlia storage from the command line.

    dahlia-disk list [--json]
    dahlia-disk add UUID --role data|parity|cache|external
    dahlia-disk remove UUID [--force]
    dahlia-disk apply
    dahlia-disk snapraid-config [--write]
    dahlia-disk settings
    dahlia-disk set-minfreespace SIZE
    dahlia-disk set-option NAME VALUE
    dahlia-disk format DEVICE --fs xfs|ext4|btrfs [--label LABEL] [--encrypt] [--json]
    dahlia-disk import UUID --to NAME [--check]
    dahlia-disk unlock [--key-file FILE] [--json]
    dahlia-disk auto-unlock on|off
    dahlia-disk passphrase
    dahlia-disk crypt-status

Passphrases come on stdin, one per line (format --encrypt, unlock, auto-unlock
on: the passphrase; passphrase: old, then new); see crypt.py.

add mounts a disk with the filesystem it has. Only format writes a new
filesystem: on a whole disk without filesystems, or one whose filesystems
import has copied to /mnt/user/NAME and verified.
"""

from __future__ import annotations

import argparse
import grp
import json
import os
import re
import subprocess
import sys
import time
from dataclasses import asdict

from . import crypt, disks, importer, snapraid, state, units

CONTROL_FILE = ".mergerfs"
BRANCHES_XATTR = "user.mergerfs.branches"
EXTERNAL_NAME_RE = re.compile(r"[^a-z0-9]+")
# XFS allows 12 characters, the shortest limit of the three.
LABEL_RE = re.compile(r"^[A-Za-z0-9_-]{1,12}$")
MKFS = {
    "xfs": ["mkfs.xfs", "-f", "-q", "-L"],
    # No blocks reserved for root: these are data disks.
    "ext4": ["mkfs.ext4", "-F", "-q", "-m", "0", "-L"],
    "btrfs": ["mkfs.btrfs", "-f", "-q", "-L"],
}


class DiskError(RuntimeError):
    pass


# --- system helpers ---------------------------------------------------------


def systemctl(*args: str) -> None:
    subprocess.run(["systemctl", *args], check=True)


def is_mounted(path: str) -> bool:
    return os.path.ismount(path)


def prepare_mountpoint(path: str) -> None:
    """Create the mount point and make it immutable while nothing is mounted.

    If a disk is missing, writes to its path then fail instead of silently
    filling the system SSD.
    """
    os.makedirs(path, exist_ok=True)
    if not is_mounted(path):
        subprocess.run(["chattr", "+i", path], check=True)


def release_mountpoint(path: str) -> None:
    if os.path.isdir(path) and not is_mounted(path):
        subprocess.run(["chattr", "-i", path], check=True)
        os.rmdir(path)


def prepare_cache_shares() -> None:
    """/mnt/cache/shares: first branch of /mnt/user, group 'dahlia' writable."""
    if os.path.isdir(units.CACHE_SHARES):
        return
    os.mkdir(units.CACHE_SHARES)
    try:
        gid = grp.getgrnam("dahlia").gr_gid
    except KeyError:
        gid = -1
    os.chown(units.CACHE_SHARES, -1, gid)
    # Group-writable with setgid: everything below stays in group 'dahlia'.
    os.chmod(units.CACHE_SHARES, 0o2775)  # noqa: S103


def has_files(path: str) -> bool:
    return any(files for _root, _dirs, files in os.walk(path))


def write_units(st: state.State) -> list[str]:
    """Write all generated units, remove stale ones. Returns current unit names."""
    rendered = units.render_all(st)
    for name, content in rendered.items():
        path = os.path.join(units.UNIT_DIR, name)
        try:
            with open(path, encoding="utf-8") as f:
                if f.read() == content:
                    continue
        except FileNotFoundError:
            pass
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
    # Drop units this tool generated earlier but that are no longer wanted.
    for name in os.listdir(units.UNIT_DIR):
        if not name.endswith(".mount") or name in rendered:
            continue
        path = os.path.join(units.UNIT_DIR, name)
        with open(path, encoding="utf-8") as f:
            generated = f.readline().startswith("# Generated by dahlia-disk")
        if generated:
            subprocess.run(
                ["systemctl", "disable", name],
                check=False,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            os.unlink(path)
    # Boot unlocking with the key file; the generator turns it into units.
    crypt.sync_crypttab([d.luks for d in st.disks if d.luks])
    systemctl("daemon-reload")
    return list(rendered)


def pool_branches_live(pool: str) -> list[str]:
    raw = os.getxattr(os.path.join(pool, CONTROL_FILE), BRANCHES_XATTR).decode()
    # Format: "/mnt/disk1=RW:/mnt/disk2=RW"
    return [b.split("=", 1)[0] for b in raw.split(":") if b]


def pool_add_branch(pool: str, branch: str, first: bool = False) -> None:
    op = "+<" if first else "+>"
    os.setxattr(os.path.join(pool, CONTROL_FILE), BRANCHES_XATTR, f"{op}{branch}".encode())


def pool_remove_branch(pool: str, branch: str) -> None:
    os.setxattr(os.path.join(pool, CONTROL_FILE), BRANCHES_XATTR, f"-{branch}".encode())


def pool_set_option(pool: str, option: str, value: str) -> None:
    os.setxattr(os.path.join(pool, CONTROL_FILE), f"user.mergerfs.{option}", value.encode())


def sync_pools(st: state.State) -> None:
    """Bring running pools in line with the state without remounting."""
    pools = units.wanted_pools(st)
    for pool in (units.STORAGE_POOL, units.USER_POOL):
        unit = units.unit_name(pool)
        if pool not in pools:
            if is_mounted(pool):
                systemctl("stop", unit)
            continue
        wanted = units.pool_branches(st, pool)
        if not is_mounted(pool):
            prepare_mountpoint(pool)
            systemctl("enable", "--now", unit)
            if not is_mounted(pool):
                raise DiskError(f"pool {pool} did not mount, see journalctl -u {unit}")
            continue
        live = pool_branches_live(pool)
        for branch in wanted:
            if branch not in live:
                pool_add_branch(pool, branch, first=branch == units.CACHE_SHARES)
        for branch in live:
            if branch not in wanted:
                pool_remove_branch(pool, branch)
        pool_set_option(pool, "category.create", units.create_policy(st, pool))
        pool_set_option(pool, "cache.files", units.CACHE_FILES)


# --- commands ---------------------------------------------------------------


def cmd_list(args) -> int:
    st = state.load()
    found = disks.classify(
        disks.run_lsblk(),
        registered_uuids={d.uuid for d in st.disks},
        allow_loop=disks.allow_loop_from_env(),
        registered_luks={d.luks for d in st.disks if d.luks},
    )
    done = importer.imported_uuids()
    for d in found:
        d.imported = bool(d.uuid) and d.uuid in done
    if args.json:
        print(json.dumps([d.to_dict() for d in found], indent=2))
        return 0
    print(f"{'DEVICE':<16} {'FS':<8} {'SIZE':>10} {'STATUS':<14} UUID / REASON")
    for d in found:
        size = f"{d.size / 1e9:.1f}G"
        print(
            f"{d.path:<16} {d.fstype or '-':<8} {size:>10} {d.status:<14} "
            f"{d.uuid or '-'}  {d.reason}"
        )
    for d in st.disks:
        mounted = "mounted" if is_mounted(d.mountpoint) else "NOT MOUNTED"
        print(f"  managed: {d.role:<8} {d.mountpoint:<24} {d.uuid}  {mounted}")
    return 0


def cmd_add(args) -> int:
    with state.locked():
        st = state.load()
        found = disks.classify(
            disks.run_lsblk(),
            registered_uuids={d.uuid for d in st.disks},
            allow_loop=disks.allow_loop_from_env(),
            registered_luks={d.luks for d in st.disks if d.luks},
        )
        dev = next((d for d in found if d.uuid == args.uuid), None)
        if dev is None:
            raise DiskError(f"no filesystem with UUID {args.uuid}")
        if args.role == "cache" and st.cache is not None:
            raise DiskError(f"a cache is already configured ({st.cache.uuid})")
        if args.role in ("data", "parity", "cache") and dev.status != "candidate":
            raise DiskError(f"{dev.path} cannot be used as {args.role}: {dev.reason}")
        if args.role == "external" and dev.status not in ("candidate", "external-only"):
            raise DiskError(f"{dev.path} cannot be mounted: {dev.reason}")

        name = ""
        if args.role == "external":
            base = EXTERNAL_NAME_RE.sub("-", (dev.label or "").lower()).strip("-")
            name = base or args.uuid.replace("-", "")[:8].lower()
            taken = {d.name for d in st.by_role("external")}
            if name in taken:
                name = f"{name}-{args.uuid.replace('-', '')[:4].lower()}"

        disk = state.Disk(
            uuid=args.uuid,
            role=args.role,
            index=0 if args.role in ("external", "cache") else st.next_index(args.role),
            fstype=dev.fstype or "",
            name=name,
            serial=dev.serial,
            model=dev.model,
            size=dev.size,
            luks=dev.luks or "",
        )
        st.disks.append(disk)
        prepare_mountpoint(disk.mountpoint)
        write_units(st)
        try:
            systemctl("enable", "--now", units.unit_name(disk.mountpoint))
            # systemctl can return 0 when only a dependency job failed.
            if not is_mounted(disk.mountpoint):
                raise subprocess.CalledProcessError(1, ["mount", disk.mountpoint])
        except subprocess.CalledProcessError:
            # Mount failed: leave the system exactly as it was.
            st.disks.remove(disk)
            subprocess.run(["systemctl", "disable", units.unit_name(disk.mountpoint)], check=False)
            write_units(st)
            release_mountpoint(disk.mountpoint)
            raise DiskError(
                f"mounting {dev.path} failed, see journalctl -u {units.unit_name(disk.mountpoint)}"
            ) from None
        if args.role == "cache":
            prepare_cache_shares()
        state.save(st)
        if args.role in ("data", "cache"):
            sync_pools(st)
        print(f"{dev.path} ({dev.fstype}) mounted at {disk.mountpoint} as {args.role}")
    return 0


def wait_for(path: str, seconds: float = 10.0) -> None:
    deadline = time.monotonic() + seconds
    while not os.path.exists(path):
        if time.monotonic() > deadline:
            raise DiskError(f"{path} did not appear after partitioning")
        time.sleep(0.2)


def check_array_key(st: state.State, key: str) -> None:
    """New encrypted disks get the passphrase the others have."""
    for d in st.disks:
        if d.luks and crypt.is_present(d.luks):
            if not crypt.key_matches(crypt.device_path(d.luks), key):
                raise DiskError("the passphrase differs from the one of the encrypted disks")
            return


def cmd_format(args) -> int:
    if not LABEL_RE.match(args.label):
        raise DiskError("label: 1 to 12 letters, digits, '-' or '_'")
    key = crypt.read_keys(sys.stdin.buffer, 1)[0] if args.encrypt else None
    with state.locked():
        st = state.load()
        if key is not None:
            check_array_key(st, key)
        found = disks.classify(
            disks.run_lsblk(),
            registered_uuids={d.uuid for d in st.disks},
            allow_loop=disks.allow_loop_from_env(),
            registered_luks={d.luks for d in st.disks if d.luks},
        )
        entries = disks.formattable(found, args.device, importer.imported_uuids())
        # Old signatures first, partitions before the disk, then one GPT
        # partition over the whole disk, type Linux filesystem.
        for e in entries:
            if e.path != e.disk:
                subprocess.run(["wipefs", "--all", "--quiet", e.path], check=True)
        subprocess.run(["wipefs", "--all", "--quiet", args.device], check=True)
        subprocess.run(["sfdisk", "--quiet", args.device], input="label: gpt\n,,L\n",
                       text=True, check=True)
        subprocess.run(["udevadm", "settle"], check=False)
        part = disks.partition_path(args.device)
        wait_for(part)
        luks = ""
        target = part
        if key is not None:
            luks = crypt.luks_format(part, key)
            if not crypt.open_with_key(part, luks, key):
                raise DiskError(f"{part}: opening the new LUKS container failed")
            if os.path.exists(crypt.KEY_FILE):
                crypt.add_key_file(part, key)
            target = crypt.mapper_path(luks)
        subprocess.run([*MKFS[args.fs], args.label, target], check=True)
        # Let udev pick up the new UUID so /dev/disk/by-uuid/ exists for add.
        subprocess.run(["udevadm", "trigger", "--action=change", target], check=False)
        subprocess.run(["udevadm", "settle"], check=False)
        uuid = disks.blkid_probe(target).get("UUID", "")
        if not uuid:
            raise DiskError(f"{target} has no filesystem UUID after mkfs")
        importer.forget({e.uuid for e in entries if e.uuid})
    if args.json:
        print(json.dumps({"device": args.device, "partition": part, "fstype": args.fs,
                          "uuid": uuid, "luks": luks}))
    else:
        inside = f" (LUKS {luks})" if luks else ""
        print(f"{args.device}: {args.fs} on {part}{inside}, UUID {uuid}")
    return 0


def cmd_import(args) -> int:
    with state.locked():
        st = state.load()
        found = disks.classify(
            disks.run_lsblk(),
            registered_uuids={d.uuid for d in st.disks},
            allow_loop=disks.allow_loop_from_env(),
            registered_luks={d.luks for d in st.disks if d.luks},
        )
        dev = importer.check_source(found, args.uuid)
        target = importer.check_target(args.to)
    if args.check:
        print(f"{dev.path} ({dev.fstype}) can be copied to {target}")
        return 0
    # Not under the storage lock: copying takes hours.
    res = importer.run_import(dev, target)
    print(f"{dev.path}: copied to {res['target']} and verified")
    return 0


def cmd_remove(args) -> int:
    with state.locked():
        st = state.load()
        disk = st.find(args.uuid)
        if disk is None:
            raise DiskError(f"UUID {args.uuid} is not managed by Dahlia")
        if disk.role == "cache" and not args.force and has_files(units.CACHE_SHARES):
            # Those files would vanish from /mnt/user.
            raise DiskError(
                f"{units.CACHE_SHARES} still holds files; run dahlia-mover first or use --force"
            )
        st.disks.remove(disk)
        # Take the branch out of the running pools before unmounting it.
        if disk.role in ("data", "cache"):
            sync_pools(st)
        unit = units.unit_name(disk.mountpoint)
        state.save(st)
        # New pool units first, so nothing depends on the disk any more,
        # then unmount it (the unit stays loaded while it is mounted).
        write_units(st)
        systemctl("stop", unit)
        release_mountpoint(disk.mountpoint)
        if disk.luks:
            crypt.close(disk.luks)
        print(f"{disk.mountpoint} unmounted and removed; data on the disk is untouched")
    return 0


def cmd_apply(args) -> int:
    with state.locked():
        st = state.load()
        for d in st.disks:
            prepare_mountpoint(d.mountpoint)
        names = write_units(st)
        missing = []
        for d in st.disks:
            systemctl("enable", "--now", units.unit_name(d.mountpoint))
            if d.luks and not crypt.is_open(d.luks):
                continue  # locked: mounts after dahlia-disk unlock
            if not is_mounted(d.mountpoint):
                missing.append(d.mountpoint)
            elif d.role == "cache":
                prepare_cache_shares()
        sync_pools(st)
        if missing:
            raise DiskError(f"not mounted: {', '.join(missing)} (disk missing or failed)")
        systemctl("enable", units.TARGET)
        print(f"{len(names)} unit(s) in place")
    return 0


def cmd_snapraid_config(args) -> int:
    st = state.load()
    text = snapraid.render(st)
    if not args.write:
        sys.stdout.write(text)
        return 0
    os.makedirs(os.path.dirname(snapraid.LOCAL_CONTENT), exist_ok=True)
    tmp = snapraid.CONFIG_PATH + ".new"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, snapraid.CONFIG_PATH)
    print(f"wrote {snapraid.CONFIG_PATH}")
    return 0


def cmd_settings(args) -> int:
    print(json.dumps(asdict(state.load().settings), indent=2))
    return 0


def cmd_set_minfreespace(args) -> int:
    with state.locked():
        st = state.load()
        if not state.SIZE_RE.match(args.size):
            raise DiskError(f"invalid size {args.size!r}, expected e.g. 50G or 500M")
        st.settings.minfreespace = args.size
        state.save(st)
        write_units(st)
        # Live pools pick the value up via their control file.
        for pool in (units.STORAGE_POOL, units.USER_POOL):
            if is_mounted(pool):
                pool_set_option(pool, "minfreespace", args.size)
        print(f"minfreespace = {args.size}")
    return 0


